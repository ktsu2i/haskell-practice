-- 直角三角形を見つける

-- * 3 辺の長さは全て整数

-- * 各辺の長さは 10 以下

-- * 周囲の長さは 24 に等しい

triples = [(a, b, c) | c <- [1 .. 10], a <- [1 .. 10], b <- [1 .. 10]]

rightTriangles = [(a, b, c) | c <- [1 .. 10], a <- [1 .. c], b <- [1 .. a], a ^ 2 + b ^ 2 == c ^ 2]

rightTriangles' = [(a, b, c) | c <- [1 .. 10], a <- [1 .. c], b <- [1 .. a], a ^ 2 + b ^ 2 == c ^ 2, a + b + c == 24]
